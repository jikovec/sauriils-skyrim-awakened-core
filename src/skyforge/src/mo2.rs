//! MO2 profile state (modlist.txt) and plugin load order (plugins.txt) generation.

use crate::config::Config;
use crate::install::State;
use crate::manifest::{Manifest, Target};
use anyhow::{anyhow, Context, Result};
use loadorder::{GameId, GameSettings};
use std::collections::HashSet;
use std::path::{Path, PathBuf};

pub const BASE_MASTERS: &[&str] = &["Skyrim.esm", "Update.esm", "Dawnguard.esm", "HearthFires.esm", "Dragonborn.esm"];

fn separator_dir(cfg: &Config, name: &str) -> PathBuf {
    cfg.mods_dir().join(format!("{name}_separator"))
}

/// Enabled MO2 mod folders, lowest priority first (manifest order).
pub fn enabled_mods<'a>(m: &'a Manifest, state: &State) -> Vec<&'a crate::manifest::ModEntry> {
    m.mods
        .iter()
        .filter(|e| e.target == Target::Mods && e.status.enabled_by_default() && state.installs.contains_key(&e.key))
        .collect()
}

/// Write modlist.txt (highest priority first) including separators, keeping
/// any MO2-managed lines skyforge does not own (e.g. "*Unmanaged" DLC entries).
pub fn write_modlist(cfg: &Config, m: &Manifest, state: &State) -> Result<usize> {
    let pdir = cfg.profile_dir();
    std::fs::create_dir_all(&pdir)?;
    let mut lines: Vec<String> = Vec::new();
    for e in &m.mods {
        if e.target != Target::Mods {
            continue;
        }
        if let Some(sep) = &e.separator {
            let d = separator_dir(cfg, sep);
            if !d.exists() {
                std::fs::create_dir_all(&d)?;
                std::fs::write(d.join("meta.ini"), "[General]\nmodid=0\nversion=\nnewestVersion=\ncategory=\ninstallationFile=\n")?;
            }
            lines.push(format!("+{sep}_separator"));
        }
        if !e.status.installs() || !state.installs.contains_key(&e.key) {
            continue;
        }
        let flag = if e.status.enabled_by_default() { '+' } else { '-' };
        lines.push(format!("{flag}{}", e.name));
    }
    lines.reverse();
    let path = pdir.join("modlist.txt");
    let mut kept = Vec::new();
    if path.exists() {
        for l in std::fs::read_to_string(&path)?.lines() {
            if l.starts_with('*') {
                kept.push(l.to_string());
            }
        }
    }
    let mut out = String::from("# This file was automatically generated by Mod Organizer.\n");
    for l in lines.iter().chain(kept.iter()) {
        out += l;
        out += "\n";
    }
    let n = lines.len();
    std::fs::write(&path, out)?;
    Ok(n)
}

/// Every plugin file provided by enabled mods: (file name, path of the winning copy).
pub fn collect_plugins(cfg: &Config, m: &Manifest, state: &State) -> Result<Vec<(String, PathBuf)>> {
    let mut seen = HashSet::new();
    let mut out = Vec::new();
    // Highest priority first, so the first copy found wins.
    for e in enabled_mods(m, state).into_iter().rev() {
        let dir = cfg.mods_dir().join(&e.name);
        let Ok(rd) = std::fs::read_dir(&dir) else { continue };
        for f in rd.flatten() {
            let name = f.file_name().to_string_lossy().to_string();
            let lower = name.to_lowercase();
            if (lower.ends_with(".esp") || lower.ends_with(".esm") || lower.ends_with(".esl")) && seen.insert(lower) {
                out.push((name, f.path()));
            }
        }
    }
    Ok(out)
}

pub struct SortResult {
    pub order: Vec<String>,
    pub masterlist: Option<PathBuf>,
}

/// Sort with libloot (LOOT masterlist + record overlap), then activate every
/// plugin from enabled mods and write the profile's plugins.txt via libloadorder.
pub fn sort_and_write(cfg: &Config, m: &Manifest, state: &State, masterlist: Option<&Path>, prelude: Option<&Path>, userlist: Option<&Path>) -> Result<SortResult> {
    let pdir = cfg.profile_dir();
    std::fs::create_dir_all(&pdir)?;
    // libloadorder uses the Windows name "Plugins.txt"; MO2 profiles use "plugins.txt". On a case-sensitive
    // filesystem those are two different files, so hand libloadorder MO2's file and rename it back after
    // saving (otherwise MO2 keeps reading a stale plugins.txt with nothing active).
    let plugins_txt = pdir.join("plugins.txt");
    let loot_plugins_txt = pdir.join("Plugins.txt");
    if plugins_txt.exists() {
        std::fs::rename(&plugins_txt, &loot_plugins_txt)?;
    } else if !loot_plugins_txt.exists() {
        std::fs::write(&loot_plugins_txt, "")?;
    }
    let data_paths: Vec<PathBuf> = enabled_mods(m, state).into_iter().rev().map(|e| cfg.mods_dir().join(&e.name)).collect();
    let plugins = collect_plugins(cfg, m, state)?;

    let mut game = libloot::Game::with_local_path(libloot::GameType::SkyrimSE, &cfg.stock_game, &pdir)
        .map_err(|e| anyhow!("libloot game handle: {e}"))?;
    game.set_additional_data_paths(data_paths.clone()).map_err(|e| anyhow!("{e}"))?;
    if let Some(ml) = masterlist {
        let db = game.database();
        let mut db = db.write().map_err(|e| anyhow!("{e}"))?;
        match prelude {
            Some(pl) => db.load_masterlist_with_prelude(ml, pl).map_err(|e| anyhow!("masterlist+prelude: {e}"))?,
            None => db.load_masterlist(ml).map_err(|e| anyhow!("masterlist: {e}"))?,
        }
    }
    if let Some(ul) = userlist {
        if ul.exists() {
            game.database().write().map_err(|e| anyhow!("{e}"))?.load_userlist(ul).map_err(|e| anyhow!("userlist: {e}"))?;
        }
    }
    let mut all: Vec<(String, PathBuf)> = BASE_MASTERS
        .iter()
        .map(|b| (b.to_string(), cfg.stock_game.join("Data").join(b)))
        .collect();
    // Creation Club / resource plugins shipped with the game (implicitly active via Skyrim.ccc).
    let ccc = std::fs::read_to_string(cfg.stock_game.join("Skyrim.ccc")).unwrap_or_default();
    for l in ccc.lines().map(str::trim).filter(|l| !l.is_empty()) {
        let p = cfg.stock_game.join("Data").join(l);
        if p.exists() {
            all.push((l.to_string(), p));
        }
    }
    all.extend(plugins.iter().cloned());
    let paths: Vec<&Path> = all.iter().map(|(_, p)| p.as_path()).collect();
    game.load_plugins(&paths).map_err(|e| anyhow!("loading plugins: {e}"))?;
    let names: Vec<&str> = all.iter().map(|(n, _)| n.as_str()).collect();
    let order = game.sort_plugins(&names).map_err(|e| anyhow!("sorting: {e}"))?;

    // Write through libloadorder so the file format matches what the game and MO2 expect.
    let mut gs = GameSettings::with_local_path(GameId::SkyrimSE, &cfg.stock_game, &pdir)
        .map_err(|e| anyhow!("libloadorder settings: {e}"))?;
    gs.set_additional_plugins_directories(data_paths);
    let mut lo = gs.into_load_order();
    lo.load().map_err(|e| anyhow!("loading load order: {e}"))?;
    let order_refs: Vec<&str> = order.iter().map(String::as_str).collect();
    lo.set_load_order(&order_refs).map_err(|e| anyhow!("set_load_order: {e}"))?;
    lo.set_active_plugins(&order_refs).map_err(|e| anyhow!("set_active_plugins: {e}"))?;
    lo.save().map_err(|e| anyhow!("saving plugins.txt: {e}"))?;
    std::fs::rename(&loot_plugins_txt, &plugins_txt).context("renaming Plugins.txt to MO2's plugins.txt")?;
    // MO2 also keeps loadorder.txt in the profile; keep it consistent.
    let mut lot = String::from("# This file was automatically generated by Mod Organizer.\n");
    for n in lo.plugin_names() {
        lot += n;
        lot += "\n";
    }
    std::fs::write(pdir.join("loadorder.txt"), lot).context("writing loadorder.txt")?;
    Ok(SortResult { order, masterlist: masterlist.map(Path::to_path_buf) })
}

/// Linux path -> Wine Z: path with backslashes.
pub fn wine_path(p: &Path) -> String {
    format!("Z:{}", p.display()).replace('/', "\\")
}

/// Set or replace `key=value` inside `[section]` of a simple INI text, preserving other content.
pub fn ini_set(text: &str, section: &str, key: &str, value: &str) -> String {
    let mut out: Vec<String> = Vec::new();
    let mut in_sec = false;
    let mut done = false;
    let mut saw_sec = false;
    for line in text.lines() {
        let t = line.trim();
        if t.starts_with('[') && t.ends_with(']') {
            if in_sec && !done {
                out.push(format!("{key}={value}"));
                done = true;
            }
            in_sec = t[1..t.len() - 1].eq_ignore_ascii_case(section);
            saw_sec |= in_sec;
            out.push(line.to_string());
            continue;
        }
        if in_sec && !done {
            if let Some((k, _)) = t.split_once('=') {
                if k.trim().eq_ignore_ascii_case(key) {
                    out.push(format!("{key}={value}"));
                    done = true;
                    continue;
                }
            }
        }
        out.push(line.to_string());
    }
    if !done {
        if !saw_sec {
            out.push(String::new());
            out.push(format!("[{section}]"));
        }
        out.push(format!("{key}={value}"));
    }
    out.join("\n") + "\n"
}

/// Point the MO2 instance at the Stock Game and create the managed profile.
pub fn setup_instance(cfg: &Config, ini_templates: &Path) -> Result<Vec<String>> {
    let mut done = Vec::new();
    let ini_path = cfg.mo2_instance.join("ModOrganizer.ini");
    let mut ini = std::fs::read_to_string(&ini_path).with_context(|| format!("reading {}", ini_path.display()))?;
    let loader = cfg.stock_game.join("skse64_loader.exe");
    if !cfg.stock_game.join("SkyrimSE.exe").exists() {
        anyhow::bail!("Stock Game not built yet ({})", cfg.stock_game.display());
    }
    let gp = wine_path(&cfg.stock_game).replace('\\', "\\\\");
    ini = ini_set(&ini, "General", "gamePath", &gp);
    ini = ini_set(&ini, "General", "selected_profile", &format!("@ByteArray({})", cfg.profile));
    ini = ini_set(&ini, "Settings", "download_directory", &wine_path(&cfg.downloads).replace('\\', "/"));
    ini = ini_set(&ini, "Settings", "lock_gui", "false");
    // No first-start tutorial prompt (blocks unattended launches) and no MO2 self-update check: the MO2
    // version is pinned by MO2-LINT and this build stays local-first.
    ini = ini_set(&ini, "General", "first_start", "false");
    ini = ini_set(&ini, "Settings", "check_for_updates", "false");
    // A single custom executable: SKSE from the Stock Game.
    let exe = wine_path(&loader).replace('\\', "/");
    let wd = wine_path(&cfg.stock_game).replace('\\', "/");
    for (k, v) in [
        ("size", "1".to_string()),
        ("1\\title", "SKSE".to_string()),
        ("1\\binary", exe),
        ("1\\arguments", String::new()),
        ("1\\workingDirectory", wd),
        ("1\\steamAppID", String::new()),
        ("1\\ownicon", "true".to_string()),
        ("1\\toolbar", "true".to_string()),
        ("1\\hide", "false".to_string()),
    ] {
        ini = ini_set(&ini, "customExecutables", k, &v);
    }
    std::fs::write(&ini_path, ini)?;
    done.push(format!("ModOrganizer.ini: gamePath -> {}", cfg.stock_game.display()));

    let pdir = cfg.profile_dir();
    std::fs::create_dir_all(pdir.join("saves"))?;
    let settings = pdir.join("settings.ini");
    if !settings.exists() {
        std::fs::write(&settings, "[General]\nLocalSaves=true\nLocalSettings=true\nAutomaticArchiveInvalidation=false\n")?;
        done.push("profile settings.ini (local saves, local INIs)".into());
    }
    for f in ["Skyrim.ini", "SkyrimPrefs.ini", "SkyrimCustom.ini"] {
        let dest = pdir.join(f);
        if !dest.exists() {
            std::fs::copy(ini_templates.join(f), &dest).with_context(|| format!("copying {f}"))?;
            done.push(format!("profile {f} from template"));
        }
    }
    for f in ["modlist.txt", "plugins.txt", "loadorder.txt"] {
        let p = pdir.join(f);
        if !p.exists() {
            std::fs::write(&p, "# This file was automatically generated by Mod Organizer.\n")?;
        }
    }
    std::fs::create_dir_all(cfg.mods_dir())?;
    std::fs::create_dir_all(cfg.mo2_instance.join("overwrite"))?;
    Ok(done)
}

#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn ini_set_replaces_and_appends() {
        let t = "[General]\ngamePath=old\n[Settings]\nfoo=1\n";
        let t2 = ini_set(t, "General", "gamePath", "new");
        assert!(t2.contains("gamePath=new") && !t2.contains("gamePath=old"));
        let t3 = ini_set(&t2, "Settings", "bar", "2");
        assert!(t3.contains("[Settings]\nfoo=1\nbar=2"));
        let t4 = ini_set(&t3, "customExecutables", "size", "1");
        assert!(t4.ends_with("[customExecutables]\nsize=1\n"));
        assert_eq!(wine_path(Path::new("/games/x y")), "Z:\\games\\x y");
    }
}
